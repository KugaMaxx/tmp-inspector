from __future__ import annotations

import math
from typing import Dict, List

from nltk.tokenize import wordpunct_tokenize
from nltk.translate.meteor_score import meteor_score
from torchmetrics.text import ROUGEScore, SQuAD


def ensure_nltk() -> None:
    """METEOR matches synonyms through WordNet, which nltk ships separately."""
    import zipfile
    from pathlib import Path

    import nltk

    for resource, package in [("corpora/wordnet", "wordnet"), ("corpora/omw-1.4", "omw-1.4")]:
        try:
            nltk.data.find(resource)
        except LookupError:
            nltk.download(package, quiet=True)
            # recent nltk downloads the zip but only reads the unpacked corpus
            archive = Path(nltk.data.find(f"{resource}.zip"))
            with zipfile.ZipFile(archive) as zf:
                zf.extractall(archive.parent)


def meteor(pred: str, target: str) -> float:
    """METEOR of one answer against one reference, both lower-cased and word-tokenised."""
    pred_tokens = wordpunct_tokenize(pred.lower())
    target_tokens = wordpunct_tokenize(target.lower())
    return meteor_score([target_tokens], pred_tokens) if pred_tokens else 0.0


class GenerationMetrics:
    """Compute and track answer metrics using torchmetrics and nltk.

    METEOR (nltk), SQuAD token F1 and ROUGE-1/2/L F-measures (torchmetrics),
    all in [0, 1] and averaged over answers.
    """

    def __init__(self):
        ensure_nltk()

        self.rouge = ROUGEScore(rouge_keys=("rouge1", "rouge2", "rougeL"))
        self.squad = SQuAD()
        # nltk has no running state, so the per-answer METEOR scores are kept here
        self._meteor: List[float] = []

    def update(self, pred: str, target: str) -> Dict[str, float]:
        """
        Score and accumulate one answer.

        Args:
            pred: Answer generated by the system.
            target: Reference answer.

        Returns:
            dict of metric-name -> score of this answer.
        """
        # forward() both accumulates the state and returns the score of this pair
        rouge = self.rouge(pred, target)
        squad = self.squad(
            [{"prediction_text": pred, "id": "0"}],
            [{"answers": {"answer_start": [0], "text": [target]}, "id": "0"}],
        )
        self._meteor.append(meteor(pred, target))

        return {
            "METEOR": self._meteor[-1],
            "F1": squad["f1"].item() / 100.0,
            "Rouge-1": rouge["rouge1_fmeasure"].item(),
            "Rouge-2": rouge["rouge2_fmeasure"].item(),
            "Rouge-L": rouge["rougeL_fmeasure"].item(),
        }

    def compute(self) -> Dict[str, float]:
        """Compute final metrics across all accumulated answers.

        Returns a dict of metric-name -> mean score.
        """
        names = ["METEOR", "F1", "Rouge-1", "Rouge-2", "Rouge-L"]
        if not self._meteor:
            return {name: float("nan") for name in names}

        rouge = self.rouge.compute()
        return {
            "METEOR": math.fsum(self._meteor) / len(self._meteor),
            "F1": self.squad.compute()["f1"].item() / 100.0,
            "Rouge-1": rouge["rouge1_fmeasure"].item(),
            "Rouge-2": rouge["rouge2_fmeasure"].item(),
            "Rouge-L": rouge["rougeL_fmeasure"].item(),
        }

    def reset(self):
        """Reset all metrics for new evaluation."""
        self.rouge.reset()
        self.squad.reset()
        self._meteor.clear()

    def summarize(self):
        """
        Summarize all computed metrics. Each column header is suffixed with an
        arrow marking that every generation metric is better high (↑).
        """
        metrics = self.compute()

        title = ""
        value = ""
        for metric_name, metric_value in metrics.items():
            header = f"{metric_name}↑"
            title += f"{header:>10s}"
            value += f"{metric_value:>10.4f}"

        return title + "\n" + value
